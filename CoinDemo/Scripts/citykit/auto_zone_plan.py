"""
Writes the plan of a street zone automatically, in the format build_zone.py reads (rebuild/zones/<Stage>_<Zone>.json),
so new zones don't need the hand measuring zone A had:

  * sidewalks: the scan's ground surface (flat, upward facing splats) raised 6-30 cm above the local road level,
    as polygons with straight-ish edges (the curb lines)
  * red pavement: where the orthophoto's road colour is reddish (Hongdae's red streets)
  * cones: orange splat clusters near the ground; poles: from scan_survey.py
  * no hero building: the zone keeps the scanned facades

  python auto_zone_plan.py Hongdae B x0 x1 y0 y1
"""

import json
import os
import sys

import numpy as np
from PIL import Image
from scipy import ndimage
from scipy.spatial import cKDTree
from shapely.geometry import Polygon
from skimage import measure

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from rebuild.common import GENERATED_DIR, SCRIPTS_DIR, Scan, ground_grid, load_collision  # noqa: E402

RES = 0.1
CURB = (0.06, 0.3)          # sidewalk height above the local road, metres
MIN_SIDEWALK = 4.0          # square metres


def main(name, zone, box):
    x0, x1, y0, y1 = box
    scan = Scan(name)
    collision = load_collision(name)
    lo, height, walls = ground_grid(collision, 0.5)
    valid = np.argwhere(~np.isnan(height))
    _, k = cKDTree(valid).query((scan.pos[:, :2] - lo) / 0.5)
    floor = height[valid[k, 0], valid[k, 1]]
    normal, flat = scan.normals()
    p = scan.pos
    sel = ((p[:, 0] > x0) & (p[:, 0] < x1) & (p[:, 1] > y0) & (p[:, 1] < y1) & (np.abs(p[:, 2] - floor) < 0.6)
           & (np.abs(normal[:, 2]) > 0.85) & (flat < 0.5) & (scan.opacity > 0.1))
    q, w = p[sel], scan.opacity[sel]
    shape = (int((x1 - x0) / RES) + 1, int((y1 - y0) / RES) + 1)
    i = ((q[:, 0] - x0) / RES).astype(int)
    j = ((q[:, 1] - y0) / RES).astype(int)
    sw, sz = np.zeros(shape), np.zeros(shape)
    np.add.at(sw, (i, j), w)
    np.add.at(sz, (i, j), w * q[:, 2])
    sw, sz = ndimage.gaussian_filter(sw, 1.5), ndimage.gaussian_filter(sz, 1.5)
    seen = sw > 0.05
    z = np.where(seen, sz / np.maximum(sw, 1e-9), np.nan)
    zf = np.where(seen, z, np.nanmedian(z))
    # local road level: a low percentile over 4 m, so raised sidewalks don't lift it
    road = ndimage.percentile_filter(zf, 20, size=int(4.0 / RES))
    rel = zf - road
    raised = seen & (rel > CURB[0]) & (rel < CURB[1])
    raised = ndimage.binary_opening(ndimage.binary_closing(raised, iterations=3), iterations=3)
    labels, n = ndimage.label(raised)
    sidewalks = {}
    for r in range(1, n + 1):
        mask = labels == r
        if mask.sum() * RES * RES < MIN_SIDEWALK:
            continue
        contour = max(measure.find_contours(np.pad(mask, 1).astype(float), 0.5), key=len)
        poly = Polygon(np.column_stack([x0 + (contour[:, 0] - 1 + 0.5) * RES, y0 + (contour[:, 1] - 1 + 0.5) * RES])).buffer(0)
        poly = poly.simplify(0.25, preserve_topology=True)
        if poly.geom_type != "Polygon" or poly.area < MIN_SIDEWALK:
            continue
        sidewalks[f"auto_{len(sidewalks) + 1:02d}"] = [[round(a, 2), round(b, 2)] for a, b in poly.exterior.coords]

    # red pavement: reddish road in the orthophoto
    info = json.load(open(os.path.join(SCRIPTS_DIR, "..", "SourceAssets", "RoadLayers", f"{name}_road.json")))
    photo = np.asarray(Image.open(os.path.join(SCRIPTS_DIR, "..", "SourceAssets", "RoadLayers", f"{name}_road.png")).convert("RGB"), float) / 255
    ox, oy = [v / 100 for v in info["origin"]]
    sx, sy = [v / 100 for v in info["size"]]
    gx = np.clip(((np.arange(x0, x1, 1.0) - ox) / sx * photo.shape[1]).astype(int), 0, photo.shape[1] - 1)
    gy = np.clip(((np.arange(y0, y1, 1.0) - oy) / sy * photo.shape[0]).astype(int), 0, photo.shape[0] - 1)
    patch = photo[gy][:, gx]
    redness = (patch[..., 0] - patch[..., 2]).mean()

    survey = json.load(open(os.path.join(GENERATED_DIR, f"{name}_survey.json")))
    poles = [[pl["x"], pl["y"]] for pl in survey["poles"] if x0 < pl["x"] < x1 and y0 < pl["y"] < y1]

    # cones: orange splat clusters 0-0.8 m up
    c = scan.colour
    orange = (c[:, 0] > 0.55) & (c[:, 1] < 0.35) & (c[:, 2] < 0.3) & (p[:, 2] - floor > 0.05) & (p[:, 2] - floor < 0.8) \
        & (p[:, 0] > x0) & (p[:, 0] < x1) & (p[:, 1] > y0) & (p[:, 1] < y1) & (scan.opacity > 0.2)
    cones = []
    if orange.any():
        g = np.zeros(shape)
        np.add.at(g, (((p[orange, 0] - x0) / RES).astype(int), ((p[orange, 1] - y0) / RES).astype(int)), 1)
        lab, m = ndimage.label(ndimage.binary_dilation(g > 0, iterations=2))
        for r in range(1, m + 1):
            if g[lab == r].sum() >= 15:
                ci, cj = np.argwhere(lab == r).mean(0)
                cones.append([round(x0 + ci * RES, 2), round(y0 + cj * RES, 2)])

    plan = {
        "_comment": ["Generated by Scripts/citykit/auto_zone_plan.py: sidewalks from the scan's ground surface (raised 6-30 cm "
                     "above the local road), red pavement from the orthophoto colour, cones from orange splat clusters, poles "
                     "from scan_survey.py. No hero building: the zone keeps the scanned facades."],
        "stage": name, "box": [x0, x1, y0, y1],
        "red_road_from_x": x0 if redness > 0.04 else x1 + 1,
        "sidewalk_height": 0.13,
        "sidewalks": sidewalks,
        "manholes": [],
        "cones": cones,
        "kit_poles": poles,
        "grates": [],
    }
    path = os.path.join(SCRIPTS_DIR, "rebuild", "zones", f"{name}_{zone}.json")
    with open(path, "w") as f:
        json.dump(plan, f, indent=1)
    print(f"{name}_{zone}: {len(sidewalks)} sidewalks ({sum(Polygon(v).area for v in sidewalks.values()):.0f} m2), "
          f"red street {redness > 0.04} ({redness:.3f}), {len(cones)} cones, {len(poles)} poles -> {path}")


main(sys.argv[1], sys.argv[2], [float(v) for v in sys.argv[3:7]])
